import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const base = process.env.ERRO_TEST_URL
if (!base || !/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base)) throw new Error('Use an isolated local browser fixture.')
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext()
const page = await context.newPage()
page.setDefaultTimeout(25_000)
const errors = []
page.on('pageerror', e => errors.push(e.message))
const field = page.getByRole('textbox', { name: 'Message E.R.R.O. AI' })
const send = page.getByRole('button', { name: 'Send message' })
async function ready() { await page.waitForFunction(() => !document.querySelector('textarea')?.readOnly && document.querySelector('select[aria-label="Saved chats"]')?.value) }
async function submit(text) {
  const before = await page.locator('.message-assistant').count()
  await field.fill(text); await send.click()
  await page.waitForFunction(n => document.querySelectorAll('.message-assistant').length === n + 1, before)
  await ready()
}
try {
  await page.goto(base); await ready()
  const firstId = await page.getByLabel('Saved chats').inputValue()
  const firstCookie = (await context.cookies()).find(c => c.name === 'erro_guest')
  assert.ok(firstCookie?.httpOnly && firstCookie.sameSite === 'Strict')
  await page.getByLabel('Attach project files').setInputFiles({ name: 'materials.csv', mimeType: 'text/csv', buffer: Buffer.from('Description,Quantity,Unit\nC16 breaker,3,pcs') })
  await page.getByText('Ready for questions', { exact: true }).waitFor()
  await page.getByLabel('Attach project files').setInputFiles({ name: 'large-notes.txt', mimeType: 'text/plain', buffer: Buffer.from('C16 panel notes and circuit labels.\n'.repeat(9000)) })
  await page.waitForFunction(() => document.querySelectorAll('.attachment').length === 2 && [...document.querySelectorAll('.attachment-progress')].every(e => e.textContent === 'Ready for questions'))
  await submit('Read this project schedule and its C16 breaker quantity')
  await page.getByText('Document sources (1)', { exact: true }).waitFor()
  await submit('a')
  assert.equal(await page.locator('.message-assistant').count(), 2, 'A one-letter follow-up must work after document analysis')
  await page.reload(); await ready()
  assert.equal(await page.locator('.message-assistant').count(), 2)
  assert.equal(await page.locator('.attachment').count(), 2)
  assert.equal((await context.cookies()).find(c => c.name === 'erro_guest').value, firstCookie.value)
  await submit('And what can you read from the same file?')
  assert.equal(await page.locator('.message-assistant').count(), 3)
  const drawing = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 120; canvas.height = 100
    const drawing = canvas.getContext('2d'); drawing.fillStyle = 'white'; drawing.fillRect(0, 0, 120, 100)
    drawing.strokeRect(20, 20, 50, 40); drawing.fillStyle = 'black'; drawing.fillText('C16 Q1', 25, 40)
    return canvas.toDataURL('image/png')
  })
  const transfer = await page.evaluateHandle(data => {
    const raw = atob(data.split(',')[1]); const bytes = Uint8Array.from(raw, c => c.charCodeAt(0))
    const transfer = new DataTransfer(); transfer.items.add(new File([bytes], 'panel.png', { type: 'image/png' })); return transfer
  }, drawing)
  await page.locator('.chat-content').dispatchEvent('drop', { dataTransfer: transfer })
  await page.waitForFunction(() => document.querySelectorAll('.attachment').length === 3 && [...document.querySelectorAll('.attachment-progress')].every(e => e.textContent === 'Ready for questions'))
  const differentImage = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 80; canvas.height = 80
    canvas.getContext('2d').fillRect(0, 0, 40, 40); return canvas.toDataURL('image/png')
  })
  await page.getByLabel('Attach project files').setInputFiles({ name: 'broken.png', mimeType: 'image/png', buffer: Buffer.from(differentImage.split(',')[1], 'base64') })
  await page.locator('.attachment-error').waitFor()
  await field.fill('A question without the failed file'); assert.ok(await send.isDisabled())
  await page.getByLabel('Use broken.png in questions').uncheck(); assert.ok(await send.isEnabled())
  await page.getByRole('button', { name: 'Remove broken.png', exact: true }).click()
  await page.getByLabel('Attach project files').setInputFiles({ name: 'too-large.pdf', mimeType: 'application/pdf', buffer: Buffer.alloc(20 * 1024 * 1024 + 1) })
  await page.getByText('Files must be nonempty and at most 20 MiB.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Remove too-large.pdf', exact: true }).click()
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), `Saved chat overflow at ${width}`)
    assert.ok(await page.getByRole('button', { name: /New chat/ }).isVisible())
    assert.ok(await page.evaluate(() => document.querySelector('.site-footer').getBoundingClientRect().top >= document.querySelector('.chat-content').getBoundingClientRect().bottom - 1))
  }
  await page.screenshot({ path: '/tmp/erro-saved-chat-mobile.png', fullPage: true })
  await page.getByRole('button', { name: /New chat/ }).click(); await ready()
  assert.notEqual(await page.getByLabel('Saved chats').inputValue(), firstId)
  assert.equal(await page.locator('.message').count(), 0); assert.equal(await page.locator('.attachment').count(), 0)
  await submit('Second saved project')
  await page.getByLabel('Saved chats').selectOption(firstId); await ready()
  assert.equal(await page.locator('.message-assistant').count(), 3)
  await page.reload(); await ready()
  assert.equal(await page.getByLabel('Saved chats').inputValue(), firstId)
  await field.fill('test-slow pending refresh'); await send.click()
  await page.getByRole('button', { name: 'Cancel reply' }).waitFor()
  await page.reload()
  await page.getByRole('button', { name: 'Cancel reply' }).waitFor()
  await page.waitForFunction(() => document.querySelectorAll('.message-assistant').length === 4)
  await ready()
  await field.fill('test-slow cancelled'); await send.click()
  await page.getByRole('button', { name: 'Cancel reply' }).click()
  await ready()
  assert.equal(await field.inputValue(), 'test-slow cancelled')
  await submit('A question after cancellation')
  await field.fill('test-error'); await send.click()
  await page.getByRole('alert').waitFor(); await ready()
  assert.equal(await field.inputValue(), 'test-error')
  await submit('b')
  const other = await browser.newContext()
  const stranger = await other.newPage()
  await stranger.goto(base)
  await stranger.waitForFunction(() => document.querySelector('select[aria-label="Saved chats"]')?.value)
  assert.equal(await stranger.locator('.message').count(), 0)
  assert.equal((await other.request.get(`${base}/api/chats/${firstId}`)).status(), 404)
  const sameBrowser = await context.newPage()
  await sameBrowser.goto(`${base}/?chat=${firstId}`)
  await sameBrowser.waitForFunction(() => document.querySelectorAll('.message-assistant').length > 0)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Delete all my data', exact: true }).click(); await ready()
  await page.waitForFunction(() => document.querySelectorAll('.message').length === 0)
  await sameBrowser.waitForFunction(() => document.querySelectorAll('.message').length === 0)
  assert.equal(await page.locator('.attachment').count(), 0)
  assert.equal(await page.getByLabel('Saved chats').locator('option').count(), 1)
  assert.notEqual((await context.cookies()).find(c => c.name === 'erro_guest').value, firstCookie.value)
  assert.equal((await context.request.get(`${base}/api/chats/${firstId}`)).status(), 404)
  assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0)
  await submit('test-clarify: Evaluate the panel plan.')
  const clarification = page.locator('.message-assistant').last()
  assert.equal(await clarification.locator('ol > li').count(), 2)
  assert.equal(await page.getByRole('heading', { name: 'Provisional evaluation' }).count(), 0)
  assert.ok(await send.isDisabled(), 'The completed questions wait for a user answer')
  await page.reload(); await ready()
  await page.getByText('Will the panel be indoors or outdoors?', { exact: true }).waitFor()
  assert.equal(await page.locator('.message-assistant').count(), 1)
  await page.screenshot({ path: '/tmp/erro-clarification-mobile.png', fullPage: true })
  await submit('Indoors. I don’t know the spare allowance; please proceed with what is supported.')
  await page.getByRole('heading', { name: 'Provisional evaluation', exact: true }).waitFor()
  assert.equal(await page.locator('.message-assistant').last().locator('ol > li').count(), 0)
  await page.reload(); await ready()
  await page.getByRole('heading', { name: 'Provisional evaluation', exact: true }).waitFor()
  assert.equal(await page.locator('.message-assistant').count(), 2)
  await page.getByRole('button', { name: /New chat/ }).click(); await ready()
  await submit('Hello')
  await page.getByText('Engineering reply.', { exact: true }).waitFor()
  assert.equal(await page.getByText('Will the panel be indoors or outdoors?', { exact: true }).count(), 0)
  assert.deepEqual(errors, [])
  await other.close()
  console.log('PASS: real PostgreSQL guest cookies, document follow-ups including one letter, refresh/pending recovery, chat switching, cancellation/errors, cross-guest isolation, deletion/cookie rotation across tabs, responsive layouts')
  console.log('PASS: two-question clarification, refresh before answering, free-text/unknown answer, resumed evaluation and new-chat isolation')
} finally { await browser.close() }
